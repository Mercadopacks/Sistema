-- Módulo "Liquidación Consolidada" (pedido 2026-11-26, ver
-- docs/liquidacion_consolidada.md para el documento de requerimiento
-- completo) — 1ra vuelta: esquema base + RPCs de generación/consulta.
-- Decisiones confirmadas con el usuario antes de escribir esto:
--   1) Vigencia de tarifas por período: en vez de reversionar TODO
--      precios_cliente (cambio de arquitectura grande, aparte, que
--      afectaría toda liquidación individual ya en producción), la
--      consolidada congela un SNAPSHOT de la tarifa propia y de
--      referencia usadas en el momento de generarse, en cada fila de
--      detalle (liquidaciones_consolidadas_detalle.tarifa_propia/
--      tarifa_referencia) — eso ya cumple la regla 5 del documento ("la
--      tarifa de referencia... debe quedar registrada en cada
--      liquidación") sin tocar precios_cliente.
--   2) La tarifa de referencia es un acuerdo configurable POR SUBCUENTA
--      (clientes_relaciones.tarifa_referencia), no necesariamente igual
--      a la tarifa propia de la cuenta principal.
--   3) La consolidada se arma SOBRE las liquidaciones individuales de
--      cada subcuenta ya generadas (estado 'generada') para ese período
--      — si a alguna le falta, la función avisa cuáles y no genera nada
--      (todo o nada, nunca parcial).

-- 1) Relación cuenta principal -> subcuenta. Tabla aparte (no un campo
--    suelto en lightdata_clientes) para poder guardar la tarifa pactada
--    por relación, desactivar sin borrar historial, y dejar lugar a más
--    niveles a futuro (una subcuenta podría ser principal de otras) sin
--    cambiar el modelo.
create table if not exists public.clientes_relaciones (
  id bigint generated by default as identity primary key,
  did_principal bigint not null references public.lightdata_clientes(did),
  did_subcuenta bigint not null references public.lightdata_clientes(did),
  -- Signo configurable (regla de negocio explícita del documento: "no debe
  -- asumir que todas las diferencias futuras necesariamente serán
  -- positivas"): 'resta' = la diferencia a favor de la subcuenta se
  -- descuenta del neto de la cuenta principal (el ejemplo del documento);
  -- 'suma' = se le suma.
  signo_ajuste text not null default 'resta' check (signo_ajuste in ('resta', 'suma')),
  tarifa_referencia numeric not null,
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  creado_por uuid references auth.users(id),
  unique(did_principal, did_subcuenta)
);
comment on table public.clientes_relaciones is 'Relación comercial cuenta principal -> subcuenta para Liquidación Consolidada. Una subcuenta no puede tener más de una relación ACTIVA a la vez (ver índice único parcial abajo) — regla de negocio 2 del documento.';

-- Regla de negocio 2 del documento: "una cuenta no debe poder asociarse
-- simultáneamente a dos cuentas principales". Índice único parcial (solo
-- sobre filas activas) en vez de una constraint simple sobre did_subcuenta
-- a secas, para poder conservar el historial de relaciones dadas de baja.
create unique index if not exists clientes_relaciones_subcuenta_activa_unica
  on public.clientes_relaciones(did_subcuenta) where activo;

alter table public.clientes_relaciones enable row level security;

-- Lectura: admin ve todas; una cuenta principal ve sus propias relaciones
-- (para que la pantalla de Liquidación Consolidada pueda armar la lista
-- de subcuentas sin depender de un admin). Reusa puede_ver_envio_de_
-- cliente() tal cual (genérica: "admin o tipo_usuario<>cliente ve todo,
-- un cliente solo si el did es alguno de los suyos").
drop policy if exists "clientes_relaciones select" on public.clientes_relaciones;
create policy "clientes_relaciones select" on public.clientes_relaciones
  for select to authenticated
  using (public.puede_ver_envio_de_cliente(did_principal));

-- Escritura (alta/baja/edición de la relación y su tarifa pactada):
-- exclusiva de personal administrativo con acceso a "admin" — una
-- subcuenta jamás pacta su propia tarifa de referencia.
drop policy if exists "clientes_relaciones admin write" on public.clientes_relaciones;
create policy "clientes_relaciones admin write" on public.clientes_relaciones
  for all to authenticated
  using (public.tiene_permiso_vista('admin'))
  with check (public.tiene_permiso_vista('admin'));

-- 2) Header de una liquidación consolidada generada para un período.
create table if not exists public.liquidaciones_consolidadas (
  id bigint generated by default as identity primary key,
  did_principal bigint not null references public.lightdata_clientes(did),
  fecha_inicio date not null,
  fecha_fin date not null,
  estado text not null default 'generada' check (estado in ('generada', 'anulada', 'pagada')),
  total_paquetes numeric not null default 0,
  importe_bruto_principal numeric not null default 0,
  total_diferencias numeric not null default 0,
  monto_neto numeric not null default 0,
  generado_en timestamptz not null default now(),
  generado_por uuid references auth.users(id),
  pagado_en timestamptz,
  anulado_en timestamptz,
  unique(did_principal, fecha_inicio, fecha_fin)
);
comment on table public.liquidaciones_consolidadas is 'Header de una Liquidación Consolidada ya generada. No se genera dos veces para la misma cuenta principal+período (unique de arriba) — ver generar_liquidacion_consolidada().';

alter table public.liquidaciones_consolidadas enable row level security;
drop policy if exists "liquidaciones_consolidadas select" on public.liquidaciones_consolidadas;
create policy "liquidaciones_consolidadas select" on public.liquidaciones_consolidadas
  for select to authenticated
  using (public.puede_ver_envio_de_cliente(did_principal));
drop policy if exists "liquidaciones_consolidadas admin write" on public.liquidaciones_consolidadas;
create policy "liquidaciones_consolidadas admin write" on public.liquidaciones_consolidadas
  for all to authenticated
  using (public.tiene_permiso_vista('admin'))
  with check (public.tiene_permiso_vista('admin'));

-- 3) Detalle por cuenta incluida (la principal + cada subcuenta). FK a la
--    liquidación individual original de esa cuenta (liquidaciones_
--    clientes) — regla 7 del documento: nunca se duplica ni se vuelve a
--    calcular esa liquidación, solo se LEE y se referencia.
create table if not exists public.liquidaciones_consolidadas_detalle (
  id bigint generated by default as identity primary key,
  liquidacion_consolidada_id bigint not null references public.liquidaciones_consolidadas(id) on delete cascade,
  did_cliente bigint not null references public.lightdata_clientes(did),
  tipo text not null check (tipo in ('principal', 'subcuenta')),
  liquidacion_cliente_id bigint not null references public.liquidaciones_clientes(id),
  cantidad_paquetes numeric not null default 0,
  tarifa_propia numeric,
  tarifa_referencia numeric,
  importe_bruto numeric not null default 0,
  signo_ajuste text check (signo_ajuste in ('resta', 'suma')),
  diferencia numeric not null default 0,
  saldo_consolidado numeric not null default 0,
  unique(liquidacion_consolidada_id, did_cliente)
);
comment on table public.liquidaciones_consolidadas_detalle is 'Snapshot congelado (tarifa_propia/tarifa_referencia tal como estaban al generar) de cada cuenta incluida en una Liquidación Consolidada — esto es lo que cumple la "vigencia por período" sin reversionar precios_cliente.';

alter table public.liquidaciones_consolidadas_detalle enable row level security;
drop policy if exists "liquidaciones_consolidadas_detalle select" on public.liquidaciones_consolidadas_detalle;
create policy "liquidaciones_consolidadas_detalle select" on public.liquidaciones_consolidadas_detalle
  for select to authenticated
  using (
    exists (
      select 1 from public.liquidaciones_consolidadas lc
      where lc.id = liquidacion_consolidada_id
        and public.puede_ver_envio_de_cliente(lc.did_principal)
    )
  );
drop policy if exists "liquidaciones_consolidadas_detalle admin write" on public.liquidaciones_consolidadas_detalle;
create policy "liquidaciones_consolidadas_detalle admin write" on public.liquidaciones_consolidadas_detalle
  for all to authenticated
  using (public.tiene_permiso_vista('admin'))
  with check (public.tiene_permiso_vista('admin'));

-- 4) RPC: subcuentas activas de una cuenta principal + si ya tienen
--    liquidación individual GENERADA para el período pedido (para que la
--    pantalla pueda mostrar "falta generar" ANTES de intentar consolidar).
create or replace function public.subcuentas_para_consolidar(
  p_did_principal bigint, p_fecha_inicio date, p_fecha_fin date
)
returns table (
  did_subcuenta bigint, nombre_fantasia text, tarifa_referencia numeric, signo_ajuste text,
  liquidacion_cliente_id bigint, liquidacion_estado text
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.puede_ver_envio_de_cliente(p_did_principal) then
    raise exception 'No autorizado a ver las subcuentas de este cliente.';
  end if;

  return query
  select cr.did_subcuenta, lc.nombre_fantasia, cr.tarifa_referencia, cr.signo_ajuste,
         liq.id, liq.estado
  from public.clientes_relaciones cr
  join public.lightdata_clientes lc on lc.did = cr.did_subcuenta
  left join public.liquidaciones_clientes liq
    on liq.did_cliente = cr.did_subcuenta
    and liq.fecha_inicio = p_fecha_inicio and liq.fecha_fin = p_fecha_fin
  where cr.did_principal = p_did_principal and cr.activo
  order by lc.nombre_fantasia;
end;
$$;
grant execute on function public.subcuentas_para_consolidar(bigint, date, date) to authenticated;

-- 5) RPC: genera la consolidada. Todo o nada — si falta la liquidación
--    individual GENERADA de alguna subcuenta activa, no genera nada y
--    devuelve el error con el detalle de qué falta (el front decide cómo
--    mostrarlo). No vuelve a calcular paquetes/montos de cada cuenta: los
--    toma tal cual de liquidaciones_clientes (regla 7, "no modificar
--    liquidaciones individuales").
create or replace function public.generar_liquidacion_consolidada(
  p_did_principal bigint, p_fecha_inicio date, p_fecha_fin date
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_id_consolidada bigint;
  v_liq_principal record;
  v_faltantes text;
  v_total_paquetes numeric := 0;
  v_total_diferencias numeric := 0;
  v_rec record;
  v_diferencia numeric;
begin
  if not public.tiene_permiso_vista('admin') then
    raise exception 'No autorizado a generar liquidaciones consolidadas.';
  end if;

  select string_agg(lc.nombre_fantasia, ', ')
    into v_faltantes
  from public.clientes_relaciones cr
  join public.lightdata_clientes lc on lc.did = cr.did_subcuenta
  left join public.liquidaciones_clientes liq
    on liq.did_cliente = cr.did_subcuenta
    and liq.fecha_inicio = p_fecha_inicio and liq.fecha_fin = p_fecha_fin
    and liq.estado = 'generada'
  where cr.did_principal = p_did_principal and cr.activo and liq.id is null;

  if v_faltantes is not null then
    raise exception 'Faltan generar liquidaciones individuales de: %', v_faltantes;
  end if;

  select * into v_liq_principal
  from public.liquidaciones_clientes
  where did_cliente = p_did_principal and fecha_inicio = p_fecha_inicio and fecha_fin = p_fecha_fin
    and estado = 'generada';
  if v_liq_principal.id is null then
    raise exception 'Falta generar la liquidación individual de la cuenta principal para este período.';
  end if;

  insert into public.liquidaciones_consolidadas (
    did_principal, fecha_inicio, fecha_fin, generado_por
  ) values (
    p_did_principal, p_fecha_inicio, p_fecha_fin, auth.uid()
  ) returning id into v_id_consolidada;

  v_total_paquetes := coalesce(v_liq_principal.cantidad_envios, 0) + coalesce(v_liq_principal.cantidad_turbo, 0);
  insert into public.liquidaciones_consolidadas_detalle (
    liquidacion_consolidada_id, did_cliente, tipo, liquidacion_cliente_id,
    cantidad_paquetes, importe_bruto, diferencia, saldo_consolidado
  ) values (
    v_id_consolidada, p_did_principal, 'principal', v_liq_principal.id,
    v_total_paquetes, v_liq_principal.monto_a_pagar, 0, v_liq_principal.monto_a_pagar
  );

  for v_rec in
    select cr.did_subcuenta, cr.tarifa_referencia, cr.signo_ajuste, liq.*
    from public.clientes_relaciones cr
    join public.liquidaciones_clientes liq
      on liq.did_cliente = cr.did_subcuenta
      and liq.fecha_inicio = p_fecha_inicio and liq.fecha_fin = p_fecha_fin
      and liq.estado = 'generada'
    where cr.did_principal = p_did_principal and cr.activo
  loop
    -- Tarifa propia "efectiva" de la subcuenta en el período: precio por
    -- paquete implícito en su propia liquidación (monto ya liquidado,
    -- dividido por los paquetes ya liquidados) — no se recalcula desde
    -- precios_cliente (que no tiene historial), se deriva de lo que esa
    -- liquidación individual YA registró como cobrado.
    declare
      v_paquetes_subcuenta numeric := coalesce(v_rec.cantidad_envios, 0) + coalesce(v_rec.cantidad_turbo, 0);
      v_tarifa_propia numeric := case when coalesce(v_rec.cantidad_envios, 0) + coalesce(v_rec.cantidad_turbo, 0) > 0
        then v_rec.monto_a_pagar / (coalesce(v_rec.cantidad_envios, 0) + coalesce(v_rec.cantidad_turbo, 0))
        else null end;
    begin
      v_diferencia := coalesce(v_tarifa_propia - v_rec.tarifa_referencia, 0) * v_paquetes_subcuenta;
      v_total_paquetes := v_total_paquetes + v_paquetes_subcuenta;
      v_total_diferencias := v_total_diferencias + v_diferencia;

      insert into public.liquidaciones_consolidadas_detalle (
        liquidacion_consolidada_id, did_cliente, tipo, liquidacion_cliente_id,
        cantidad_paquetes, tarifa_propia, tarifa_referencia, importe_bruto,
        signo_ajuste, diferencia, saldo_consolidado
      ) values (
        v_id_consolidada, v_rec.did_subcuenta, 'subcuenta', v_rec.id,
        v_paquetes_subcuenta, v_tarifa_propia, v_rec.tarifa_referencia, v_rec.monto_a_pagar,
        v_rec.signo_ajuste, v_diferencia,
        case when v_rec.signo_ajuste = 'suma' then v_diferencia else -v_diferencia end
      );
    end;
  end loop;

  update public.liquidaciones_consolidadas
  set total_paquetes = v_total_paquetes,
      importe_bruto_principal = v_liq_principal.monto_a_pagar,
      total_diferencias = v_total_diferencias,
      monto_neto = (
        select coalesce(sum(saldo_consolidado), 0)
        from public.liquidaciones_consolidadas_detalle
        where liquidacion_consolidada_id = v_id_consolidada
      )
  where id = v_id_consolidada;

  return v_id_consolidada;
end;
$$;
grant execute on function public.generar_liquidacion_consolidada(bigint, date, date) to authenticated;

-- 6) RPC: trae header + detalle de una consolidada ya generada (para
--    pintar la pantalla), acotado por el mismo guard que el resto.
create or replace function public.obtener_liquidacion_consolidada(p_id bigint)
returns table (
  id bigint, did_principal bigint, fecha_inicio date, fecha_fin date, estado text,
  total_paquetes numeric, importe_bruto_principal numeric, total_diferencias numeric, monto_neto numeric,
  detalle jsonb
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_lc record;
begin
  select * into v_lc from public.liquidaciones_consolidadas where liquidaciones_consolidadas.id = p_id;
  if v_lc.id is null or not public.puede_ver_envio_de_cliente(v_lc.did_principal) then
    raise exception 'No autorizado o liquidación consolidada inexistente.';
  end if;

  return query
  select v_lc.id, v_lc.did_principal, v_lc.fecha_inicio, v_lc.fecha_fin, v_lc.estado,
         v_lc.total_paquetes, v_lc.importe_bruto_principal, v_lc.total_diferencias, v_lc.monto_neto,
         (
           select jsonb_agg(jsonb_build_object(
             'did_cliente', d.did_cliente, 'nombre_fantasia', lcli.nombre_fantasia, 'tipo', d.tipo,
             'cantidad_paquetes', d.cantidad_paquetes, 'tarifa_propia', d.tarifa_propia,
             'tarifa_referencia', d.tarifa_referencia, 'importe_bruto', d.importe_bruto,
             'signo_ajuste', d.signo_ajuste, 'diferencia', d.diferencia, 'saldo_consolidado', d.saldo_consolidado
           ) order by d.tipo desc, lcli.nombre_fantasia)
           from public.liquidaciones_consolidadas_detalle d
           join public.lightdata_clientes lcli on lcli.did = d.did_cliente
           where d.liquidacion_consolidada_id = v_lc.id
         );
end;
$$;
grant execute on function public.obtener_liquidacion_consolidada(bigint) to authenticated;

-- 7) Anular (regla 10: una liquidación pagada no se modifica
--    automáticamente — anular queda bloqueado si ya está 'pagada').
create or replace function public.anular_liquidacion_consolidada(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.tiene_permiso_vista('admin') then
    raise exception 'No autorizado.';
  end if;
  update public.liquidaciones_consolidadas
  set estado = 'anulada', anulado_en = now()
  where id = p_id and estado = 'generada';
  if not found then
    raise exception 'Solo se puede anular una consolidada en estado "generada".';
  end if;
end;
$$;
grant execute on function public.anular_liquidacion_consolidada(bigint) to authenticated;

-- 8) Marcar como pagada.
create or replace function public.marcar_pagada_liquidacion_consolidada(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if not public.tiene_permiso_vista('admin') then
    raise exception 'No autorizado.';
  end if;
  update public.liquidaciones_consolidadas
  set estado = 'pagada', pagado_en = now()
  where id = p_id and estado = 'generada';
  if not found then
    raise exception 'Solo se puede marcar como pagada una consolidada en estado "generada".';
  end if;
end;
$$;
