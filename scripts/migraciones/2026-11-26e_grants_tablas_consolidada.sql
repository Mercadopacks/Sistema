-- Bug real 2026-11-26: "permission denied for table clientes_relaciones"
-- al intentar vincular — las 3 tablas nuevas de Liquidación Consolidada
-- (clientes_relaciones, liquidaciones_consolidadas, liquidaciones_
-- consolidadas_detalle) se crearon con RLS + políticas bien definidas,
-- pero SIN el GRANT de tabla en sí al rol `authenticated` — en Postgres,
-- RLS filtra FILAS, pero antes de eso el rol necesita el permiso de
-- COMANDO (select/insert/update/delete) sobre la tabla completa, o
-- Postgres corta con "permission denied" sin llegar siquiera a evaluar
-- las políticas. Mismo patrón recurrente ya documentado en memoria
-- (feedback_grants_tablas_nuevas): toda migración "create table" nueva
-- necesita su GRANT explícito, las políticas RLS solas no alcanzan.
grant select, insert, update, delete on public.clientes_relaciones to authenticated;
grant select, insert, update, delete on public.liquidaciones_consolidadas to authenticated;
grant select, insert, update, delete on public.liquidaciones_consolidadas_detalle to authenticated;

-- Las 3 tablas usan secuencias identity (generated by default as identity)
-- — el INSERT también necesita permiso de uso sobre esas secuencias.
grant usage, select on sequence public.clientes_relaciones_id_seq to authenticated;
grant usage, select on sequence public.liquidaciones_consolidadas_id_seq to authenticated;
grant usage, select on sequence public.liquidaciones_consolidadas_detalle_id_seq to authenticated;

notify pgrst, 'reload schema';
